#!/bin/bash
# Does every command the entries know exist everywhere it should, with the
# same words? The menus are the source - the way-in menu of wsl-fleet.ps1 and the
# console menu of Start-Cli.ps1; the README table and the commands page (its
# table, its section, its two sample menus) are the copies that drift.
#
# A command is a menu word with a gesture behind it: the way-in menu's 'cli'
# opens the console's menu, not a gesture, and the docs owe it nothing.
#
# It reads, it never writes: safe to run anywhere, on any branch.
#
# Usage: bash tests/tree/doc-drift.sh
set -u

# From this file's own folder, two levels up: tests/ sits at the root.
cd "$(dirname "$0")/../.." || exit 1

entry=$(tr -d '\r' < wsl-fleet.ps1)
console=$(tr -d '\r' < src/windows/Start-Cli.ps1)
drift=0

# The words of both menus, with the gesture each rides on: the way-in menu is
# wsl-fleet.ps1's own; the console menu's rows are read from Start-Cli.ps1, and the
# gesture that answers the word from the $gestures table.
names=$( {
    printf '%s\n' "$entry" | sed -n 's/^ *Add("\([a-z_]*\)".*/\1/p'
    # The pattern is the menu's own text, not a shell expansion of this script.
    # shellcheck disable=SC2016
    printf '%s\n' "$console" | sed -n 's/^$menu = $menu\.Add("\([a-z_]*\)".*/\1/p'
} | while read -r name; do
    if [ "$name" = "gui" ]; then
        [ -f "src/windows/Start-Gui.ps1" ] && echo "$name"
    elif [ "$name" = "cli" ]; then
        :                        # opens the console's menu; the docs owe it nothing
    else
        printf '%s\n' "$console" | grep -q "^    \"$name\"\{1,\}[ ]*=" && echo "$name"
    fi
done)

printf "%-14s %-8s %-7s %-7s %-7s %-8s %-8s\n" COMMAND README TABLE SECTION SAMPLE WHAT@README WHAT@PAGE
while read -r name; do
    [ -z "$name" ] && continue
    what=$(printf '%s\n%s\n' "$entry" "$console" | sed -n "s/.*Add(\"$name\", *\"\([^\"]*\)\".*/\1/p" | head -1)

    ok() { if [ "$1" -gt 0 ]; then echo ok; else echo MISSING; drift=1; fi; }
    r=$(ok "$(grep -c "wsl-fleet\.ps1 $name\`\](docs/wsl/commands.md#$name)" README.md)")
    t=$(ok "$(grep -c "wsl-fleet\.ps1 $name\`\](#$name)" docs/wsl/commands.md)")
    s=$(ok "$(grep -c "^## \`$name\`" docs/wsl/commands.md)")
    # the sample line, whole: name AND description, spaces included
    sm=$(ok "$(grep -cF "$(printf '%-12s %s' "$name" "$what")" docs/wsl/commands.md)")
    wr=$(ok "$(grep -cF "| $what |" README.md)")
    wt=$(ok "$(grep -cF "| $what |" docs/wsl/commands.md)")
    { [ "$wr" = "MISSING" ] || [ "$wt" = "MISSING" ]; } && drift=1
    printf "%-14s %-8s %-7s %-7s %-7s %-8s %-8s\n" "$name" "$r" "$t" "$s" "$sm" "$wr" "$wt"
done <<< "$names"

# And the other way round: a command the docs still offer that the entries no
# longer know. The loop above reads the menus and cannot see one - all three
# copies are checked. The docs tables are matched on their own shape -
# ".\wsl-fleet.ps1 <name>" - so that prose naming wsl-fleet.ps1 without the dot-slash is not
# read as a command.
while read -r name; do
    { grep -q "Add(\"$name\"" wsl-fleet.ps1 || grep -q "\"$name\"\{1,\}[ ]*=" src/windows/Start-Cli.ps1; } || {
        echo "  EXTRA: '$name' is offered by the docs, and the entries do not know it"
        drift=1
    }
done < <(grep -ohE '\\wsl-fleet\.ps1 [a-z_]+' README.md docs/wsl/commands.md | awk '{print $2}' | sort -u)

# The sample menus on the commands page are copies too, and the ones that
# drift most easily: they are regenerated by hand. Each block only, from its
# title down to its footer - the page documents other menus of its own, drawn
# the same way at the same indent, and their rows are not commands of the
# entries. The title is the anchor: a moved title leaves the block empty, and
# empty is reported rather than passed - a check that reads nothing says
# nothing.
check_sample() {
    local title="$1" source="$2"
    local rows
    rows=$(awk -v t="$title" '
        $0 == t { on=1; next }
        on && /^  up\/down to move/ { exit }
        on && match($0, /^  (> )?[a-z_]+/) {
            w = $0
            sub(/^  (> )?/, "", w)
            sub(/ .*/, "", w)
            print w
        }' docs/wsl/commands.md | sort -u)
    if [ -z "$rows" ]; then
        echo "  EXTRA: no sample menu found under '$title' - this check read nothing"
        drift=1
        return
    fi
    while read -r name; do
        [ -z "$name" ] && continue
        grep -q "Add(\"$name\"" "$source" || {
            echo "  EXTRA: the sample menu '$title' shows '$name', and $source does not know it"
            drift=1
        }
    done <<< "$rows"
}
check_sample "Wsl Fleet" wsl-fleet.ps1
check_sample "WSL Fleet CLI" src/windows/Start-Cli.ps1

echo
[ "$drift" -eq 0 ] && echo "VERDICT: no drift" || echo "VERDICT: drift"
exit $drift
