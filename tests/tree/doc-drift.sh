#!/bin/bash
# Does every command the entries know exist in the CLI guide, with the same
# words? The menus are the source - the way-in menu of wsl-fleet.ps1 and the
# console menu of Start-Cli.ps1; docs/user-cli.md is the copy that drifts.
#
# gui and cli are the ways in, not commands: the README's User Guide owns them,
# and the guide links both user pages back to it.
#
# It reads, it never writes: safe to run anywhere, on any branch.
#
# Usage: bash tests/tree/doc-drift.sh
set -u

# From this file's own folder, two levels up: tests/ sits at the root.
cd "$(dirname "$0")/../.." || exit 1

entry=$(tr -d '\r' < wsl-fleet.ps1)
console=$(tr -d '\r' < src/windows/Start-Cli.ps1)
drift=0

# The words of both menus, with the gesture each rides on: the way-in menu is
# wsl-fleet.ps1's own; the console menu's rows are read from Start-Cli.ps1, and the
# gesture that answers the word from the $gestures table.
names=$( {
    printf '%s\n' "$entry" | sed -n 's/^ *Add("\([a-z_]*\)".*/\1/p'
    # The pattern is the menu's own text, not a shell expansion of this script.
    # shellcheck disable=SC2016
    printf '%s\n' "$console" | sed -n 's/^$menu = $menu\.Add("\([a-z_]*\)".*/\1/p'
} | while read -r name; do
    if [ "$name" = "gui" ]; then
        [ -f "src/windows/Start-Gui.ps1" ] && echo "$name"
    elif [ "$name" = "cli" ]; then
        :                        # the way in, not a command: the docs owe it nothing
    else
        printf '%s\n' "$console" | grep -q "^    \"$name\"\{1,\}[ ]*=" && echo "$name"
    fi
done)

printf "%-14s %-6s %-8s %-8s\n" COMMAND TABLE SECTION WHAT@GUIDE
while read -r name; do
    [ -z "$name" ] && continue
    [ "$name" = "gui" ] && continue
    what=$(printf '%s\n%s\n' "$entry" "$console" | sed -n "s/.*Add(\"$name\", *\"\([^\"]*\)\".*/\1/p" | head -1)

    ok() { if [ "$1" -gt 0 ]; then echo ok; else echo MISSING; drift=1; fi; }
    t=$(ok "$(grep -c "](#$name)" docs/user-cli.md)")
    s=$(ok "$(grep -c "^## \`$name\`" docs/user-cli.md)")
    w=$(ok "$(grep -cF "| $what |" docs/user-cli.md)")
    printf "%-14s %-6s %-8s %-8s\n" "$name" "$t" "$s" "$w"
done <<< "$names"

# The README's User Guide links both pages, and each links back to it.
grep -q "docs/user-cli.md" README.md || {
    echo "  EXTRA: the README's User Guide does not link docs/user-cli.md"
    drift=1
}
grep -q "docs/user-gui.md" README.md || {
    echo "  EXTRA: the README's User Guide does not link docs/user-gui.md"
    drift=1
}
for page in docs/user-cli.md docs/user-gui.md; do
    grep -q "../README.md#user-guide" "$page" || {
        echo "  EXTRA: '$page' carries no link back to the README's User Guide"
        drift=1
    }
done

# And the other way round: a section the guide still offers that the entries no
# longer know. The backticks below are the guide's own markdown, not a command
# substitution.
# shellcheck disable=SC2016
while read -r name; do
    { grep -q "Add(\"$name\"" wsl-fleet.ps1 || grep -q "\"$name\"\{1,\}[ ]*=" src/windows/Start-Cli.ps1; } || {
        echo "  EXTRA: '$name' is offered by the guide, and the entries do not know it"
        drift=1
    }
done < <(grep -ohE '^## `[a-z_]+`' docs/user-cli.md | tr -d '#` ' | sort -u)

# The sample menus in the guide are copies too, and the ones that drift most
# easily: they are regenerated by hand. Each block only, from its title down to
# its footer. The title is the anchor: a moved title leaves the block empty,
# and empty is reported rather than passed - a check that reads nothing says
# nothing.
check_sample() {
    local title="$1" source="$2"
    local rows
    rows=$(awk -v t="$title" '
        $0 == t { on=1; next }
        on && /^  up\/down to move/ { exit }
        on && match($0, /^  (> )?[a-z_]+/) {
            w = $0
            sub(/^  (> )?/, "", w)
            sub(/ .*/, "", w)
            print w
        }' docs/user-cli.md | sort -u)
    if [ -z "$rows" ]; then
        echo "  EXTRA: no sample menu found under '$title' - this check read nothing"
        drift=1
        return
    fi
    while read -r name; do
        [ -z "$name" ] && continue
        grep -q "Add(\"$name\"" "$source" || {
            echo "  EXTRA: the sample menu '$title' shows '$name', and $source does not know it"
            drift=1
        }
    done <<< "$rows"
}
check_sample "WSL Fleet CLI" src/windows/Start-Cli.ps1

echo
[ "$drift" -eq 0 ] && echo "VERDICT: no drift" || echo "VERDICT: drift"
exit $drift
